// query: w=960&delay=400
// 保存在途（每个接口延迟 400ms）：期间接着打字不丢、仍算未保存；期间不能换编辑对象（点别的条目、方向键、切页签、编辑别的章）。
async () => {
  const w = (ms) => new Promise((r) => setTimeout(r, ms))
  const $ = (s) => document.querySelector(s)
  const $$ = (s) => Array.from(document.querySelectorAll(s))
  const out = []
  const check = (label, cond) => out.push((cond ? 'PASS ' : 'FAIL ') + label)
  const input = (el, value) => {
    const proto = el.tagName === 'TEXTAREA' ? HTMLTextAreaElement.prototype : HTMLInputElement.prototype
    Object.getOwnPropertyDescriptor(proto, 'value').set.call(el, value)
    el.dispatchEvent(new Event('input', { bubbles: true }))
  }
  const key = (el, k, o) => el.dispatchEvent(new KeyboardEvent('keydown', Object.assign({ key: k, bubbles: true, cancelable: true }, o || {})))
  const posts = (p) => window.__harness.posts.filter((x) => x.path === p)
  const tab = (i) => $$('.wsm-tab')[i].click()

  // —— 记忆
  tab(3)
  await w(300)
  const body = () => $('.wsm-editor textarea.wsm-field')
  const selected = () => $('.wsm-row[aria-selected="true"]')?.getAttribute('data-key')
  const sel0 = selected()
  body().focus()
  input(body(), body().value + '\n第一处')
  await w(50)
  key(body(), 's', { ctrlKey: true })
  await w(100)
  input(body(), body().value + '\n途中第二段')
  await w(50)
  $$('.wsm-row').find((r) => r.getAttribute('data-key') !== sel0).click()
  await w(50)
  key($('.wsm-row[aria-selected="true"]'), 'ArrowDown')
  await w(50)
  tab(0)
  await w(50)
  check('memory save in flight: clicking another entry / arrow keys / tabs opens no guard', !$('dialog[open]'))
  check('memory save in flight: selection unchanged', selected() === sel0)
  check('memory save in flight: still on the memories page', $$('.wsm-tab')[3].getAttribute('aria-selected') === 'true')
  await w(1300)
  const saves = posts('/save')
  check('memory: the request carried the first edit only', saves.length === 1 && saves[0].body.patch.body.endsWith('第一处'))
  check('memory: text typed during the save is still there', body().value.endsWith('途中第二段'))
  check('memory: still marked unsaved (save bar + tab dot)', !!$('.wsm-savebar') && !!$('.wsm-tab-dot'))
  $$('.wsm-savebar .wsm-btn')[0].click()
  await w(120)
  $$('dialog[open] .wsm-dialog-foot .wsm-btn')[1].click()
  await w(120)

  // —— 章节
  tab(2)
  await w(300)
  $$('.wsm-chap')[1].querySelector('.wsm-chap-actions .wsm-btn').click()
  await w(150)
  const ta = () => $('.wsm-chap-edit textarea')
  ta().focus()
  input(ta(), ta().value + '\nA-第一处')
  await w(50)
  key(ta(), 's', { ctrlKey: true })
  await w(100)
  input(ta(), ta().value + '\nA-途中')
  await w(50)
  $$('.wsm-chap')[2].querySelector('.wsm-chap-actions .wsm-btn').click()
  await w(80)
  check('chapter save in flight: editing another chapter opens no guard', !$('dialog[open]'))
  check('chapter save in flight: still editing chapter 2', !!$('.wsm-chap-edit') && $$('.wsm-chap')[1].contains($('.wsm-chap-edit')))
  await w(1400)
  const chap = posts('/agents/save-section')
  check('chapter: the request carried the first edit only', chap.length === 1 && chap[0].body.body.endsWith('A-第一处'))
  check('chapter: editor stays open with the text typed during the save', !!ta() && ta().value.endsWith('A-途中'))
  check('chapter: still unsaved (save button enabled)', !!$('.wsm-chap-edit-foot .wsm-btn[data-variant="primary"]') && !$('.wsm-chap-edit-foot .wsm-btn[data-variant="primary"]').disabled)
  key(ta(), 's', { ctrlKey: true })
  await w(1400)
  const chap2 = posts('/agents/save-section')
  check('chapter: saving again sends the late text and closes the editor', chap2.length === 2 && chap2[1].body.body.endsWith('A-途中') && !$('.wsm-chap-edit'))
  return out.join('\n')
}
